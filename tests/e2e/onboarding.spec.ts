import { expect, test } from '@playwright/test'

test('first-use tutorial can be completed, skipped, and replayed in either language', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/settings')
  const tutorial = page.locator('.getting-started')
  await expect(tutorial).toBeVisible()
  await expect(tutorial).toContainText('第 1 步，共 3 步')
  await page.locator('#ui-language').selectOption('en')
  await expect(tutorial).toContainText('Start with one word')
  await tutorial.getByRole('button', { name: 'Try a word', exact: true }).click()
  await expect(page).toHaveURL(/\/lookup\?q=resilient$/)
  await expect(page.getByRole('textbox', { name: 'Word search input' })).toHaveValue('resilient')
  await tutorial.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(tutorial).toContainText('Add words to a study list')
  await tutorial.getByRole('button', { name: 'Open Lists', exact: true }).click()
  await expect(page).toHaveURL(/\/lists$/)
  await tutorial.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(tutorial).toContainText('Step 1 of 3')
  await tutorial.getByRole('button', { name: 'Next', exact: true }).click()
  await tutorial.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(tutorial).toContainText('Recall first, then reveal')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results/tutorial-en-mobile.png', fullPage: true })
  await tutorial.getByRole('button', { name: 'Finish tutorial', exact: true }).click()
  await page.reload()
  await expect(tutorial).toBeHidden()
  await page.locator('.bottom-nav a[href="/settings"]').click()
  await page.getByRole('button', { name: 'Replay tutorial', exact: true }).click()
  await expect(tutorial).toContainText('Step 1 of 3')
  await tutorial.getByRole('button', { name: 'Skip tutorial', exact: true }).click()
  await page.reload()
  await expect(tutorial).toBeHidden()
})
